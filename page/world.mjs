const BOUNDS = { west: -130, east: 180, north: 74, south: -48 };

export function projector(width, height) {
  const perDegX = width / (BOUNDS.east - BOUNDS.west);
  const perDegY = height / (BOUNDS.north - BOUNDS.south);
  return ([lat, lon]) => [(lon - BOUNDS.west) * perDegX, (BOUNDS.north - lat) * perDegY];
}

export function landPaths(width, height, fill) {
  const place = projector(width, height);
  return Object.values(LAND).map((ring) => {
    const pts = ring.split(' ').map((pair) => {
      const [lon, lat] = pair.split(',').map(Number);
      return place([lat, lon]).map((v) => v.toFixed(1)).join(' ');
    });
    return `<path d="M${pts.join('L')}Z" fill="${fill}"/>`;
  }).join('');
}

// Pins that fall on top of one another are pushed apart a little, so each number stays readable.
export function spread(points, gap, rounds = 60) {
  const pts = points.map((p) => ({ ...p }));
  for (let r = 0; r < rounds; r++) {
    for (let i = 0; i < pts.length; i++) {
      for (let j = i + 1; j < pts.length; j++) {
        const dx = pts[j].x - pts[i].x;
        const dy = pts[j].y - pts[i].y;
        const d = Math.hypot(dx, dy) || 0.01;
        const need = gap(pts[i], pts[j]);
        if (d >= need) continue;
        const push = (need - d) / 2;
        const ux = dx / d || 0.7;
        const uy = dy / d || 0.7;
        pts[i].x -= ux * push; pts[i].y -= uy * push;
        pts[j].x += ux * push; pts[j].y += uy * push;
      }
    }
  }
  return pts;
}
